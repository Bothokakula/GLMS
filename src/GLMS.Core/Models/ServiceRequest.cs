// File: Models/ServiceRequest.cs
// Purpose: Defines the ServiceRequest domain entity. A service request is a billable
//          work item raised against an active contract. Costs are captured in both
//          USD (source) and ZAR (converted) to support multi-currency reporting.

using System.ComponentModel.DataAnnotations;
using System.ComponentModel.DataAnnotations.Schema;

namespace GLMS.Core.Models;

/// <summary>
/// Represents a single service request (work item) associated with a
/// <see cref="Contract"/>. Stores cost information in dual currencies and
/// records the exchange rate at the time of creation for audit traceability.
/// </summary>
public class ServiceRequest
{
    /// <summary>
    /// Primary key generated by the database.
    /// </summary>
    public int Id { get; set; }

    /// <summary>
    /// Foreign key to the parent <see cref="Contract"/>. Required because a
    /// service request cannot exist independently of a contract.
    /// </summary>
    [Required]
    public int ContractId { get; set; }

    /// <summary>
    /// Free-text description of the work being requested.
    /// </summary>
    [Required]
    [MaxLength(1000)]
    public string Description { get; set; } = string.Empty;

    /// <summary>
    /// Cost of the service request in US Dollars (source currency).
    /// Precision set to 18,2 to match typical financial column constraints.
    /// </summary>
    [Column(TypeName = "decimal(18,2)")]
    public decimal CostUSD { get; set; }

    /// <summary>
    /// Cost of the service request in South African Rand (converted currency).
    /// Calculated at creation time using the live exchange rate.
    /// </summary>
    [Column(TypeName = "decimal(18,2)")]
    public decimal CostZAR { get; set; }

    /// <summary>
    /// The USD→ZAR exchange rate captured at the moment the request was created.
    /// Stored with higher precision (18,6) so conversions can be independently verified.
    /// </summary>
    [Column(TypeName = "decimal(18,6)")]
    public decimal ExchangeRate { get; set; }

    /// <summary>
    /// Workflow status of the request (e.g. "Pending", "Active", "Cancelled", "Suspended").
    /// Defaults to "Pending" on creation. May be updated by
    /// <see cref="Services.Observers.ServiceRequestStatusObserver"/> when the parent
    /// contract's status changes.
    /// </summary>
    [Required]
    [MaxLength(50)]
    public string Status { get; set; } = "Pending";

    /// <summary>
    /// UTC timestamp of when the service request was created.
    /// Defaults to <see cref="DateTime.UtcNow"/> to ensure consistent time-zone handling.
    /// </summary>
    public DateTime CreatedDate { get; set; } = DateTime.UtcNow;

    /// <summary>
    /// Navigation property to the parent <see cref="Contract"/>.
    /// </summary>
    [ForeignKey(nameof(ContractId))]
    public Contract Contract { get; set; } = null!;
}
