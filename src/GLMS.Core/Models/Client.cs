// File: Models/Client.cs
// Purpose: Defines the Client domain entity representing an organisation or individual
//          that holds one or more licence/service contracts within the GLMS system.
// Pattern: Plain Entity / Anemic Domain Model — state is managed externally by services
//          and repositories, keeping the model focused on data integrity via data annotations.

using System.ComponentModel.DataAnnotations;

namespace GLMS.Core.Models;

/// <summary>
/// Represents a client (organisation or individual) that can hold licence contracts.
/// Serves as the aggregate root for the Client → Contract relationship, ensuring
/// every contract is always associated with a known client.
/// </summary>
public class Client
{
    /// <summary>
    /// Primary key generated by the database. Used as the stable identifier for
    /// look-ups, foreign-key relationships, and API resource URIs.
    /// </summary>
    public int Id { get; set; }

    /// <summary>
    /// Legal or trading name of the client. Required because every contract must
    /// reference a named party for audit and reporting purposes.
    /// </summary>
    [Required]
    [MaxLength(200)]
    public string Name { get; set; } = string.Empty;

    /// <summary>
    /// Primary contact e-mail address. Validated with <see cref="EmailAddressAttribute"/>
    /// to prevent malformed addresses from entering the system, since automated
    /// notifications may be sent to this address.
    /// </summary>
    [Required]
    [EmailAddress]
    [MaxLength(256)]
    public string Email { get; set; } = string.Empty;

    /// <summary>
    /// Contact telephone number. Optional but validated for format when provided,
    /// so downstream integrations (e.g. SMS alerts) receive a usable value.
    /// </summary>
    [Phone]
    [MaxLength(20)]
    public string Phone { get; set; } = string.Empty;

    /// <summary>
    /// Geographic region the client operates in (e.g. "EMEA", "APAC").
    /// Used for filtering and regional reporting.
    /// </summary>
    [MaxLength(100)]
    public string Region { get; set; } = string.Empty;

    /// <summary>
    /// Navigation property to the contracts held by this client.
    /// Initialised to an empty list so callers never encounter a null collection.
    /// </summary>
    public ICollection<Contract> Contracts { get; set; } = new List<Contract>();
}
