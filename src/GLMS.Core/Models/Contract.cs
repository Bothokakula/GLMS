// File: Models/Contract.cs
// Purpose: Defines the Contract domain entity, the central business object in the GLMS
//          system. A contract records the agreement between a client and the service
//          provider, including its lifecycle status, service tier, and signed document.
// Pattern: Plain Entity — lifecycle transitions are enforced externally via the
//          Strategy pattern for validation and the Observer pattern for side-effects
//          (Gamma, E., Helm, R., Johnson, R. and Vlissides, J. (1994) Design Patterns:
//          Elements of Reusable Object-Oriented Software).

using System.ComponentModel.DataAnnotations;
using System.ComponentModel.DataAnnotations.Schema;

namespace GLMS.Core.Models;

/// <summary>
/// Represents a licence or service contract between the organisation and a
/// <see cref="Client"/>. Tracks the contract's validity period, service level,
/// current lifecycle status, and an optional signed agreement document.
/// </summary>
public class Contract
{
    /// <summary>
    /// Primary key generated by the database.
    /// </summary>
    public int Id { get; set; }

    /// <summary>
    /// Foreign key to the owning <see cref="Client"/>. Required because
    /// every contract must belong to exactly one client.
    /// </summary>
    [Required]
    public int ClientId { get; set; }

    /// <summary>
    /// Human-readable title summarising the contract's purpose
    /// (e.g. "Annual Premium Support 2025").
    /// </summary>
    [Required]
    [MaxLength(300)]
    public string Title { get; set; } = string.Empty;

    /// <summary>
    /// Date the contract becomes effective. Used together with <see cref="EndDate"/>
    /// to determine the active window.
    /// </summary>
    public DateTime StartDate { get; set; }

    /// <summary>
    /// Date the contract expires. The <see cref="Services.ContractFactory"/> may
    /// adjust this automatically when an invalid or missing end date is supplied,
    /// based on the chosen <see cref="ServiceLevel"/>.
    /// </summary>
    public DateTime EndDate { get; set; }

    /// <summary>
    /// Current lifecycle status of the contract (Draft → Active → Expired / OnHold).
    /// Valid transitions are enforced by <see cref="Services.Validation.ContractStatusValidationStrategy"/>.
    /// </summary>
    public ContractStatus Status { get; set; }

    /// <summary>
    /// Tier of service (Standard or Premium). Determines business rules such as
    /// default contract duration and eligibility for certain operations.
    /// </summary>
    public ServiceLevel ServiceLevel { get; set; }

    /// <summary>
    /// Server-side file path to the signed PDF agreement, if one has been uploaded.
    /// Null when no document has been attached yet.
    /// </summary>
    [MaxLength(500)]
    public string? SignedAgreementPath { get; set; }

    /// <summary>
    /// Original file name provided by the user at upload time. Preserved so the
    /// download can be served with a meaningful name rather than the GUID-based
    /// storage name.
    /// </summary>
    [MaxLength(256)]
    public string? OriginalFileName { get; set; }

    /// <summary>
    /// Navigation property to the parent <see cref="Client"/>. Configured via
    /// the <see cref="ForeignKeyAttribute"/> on <see cref="ClientId"/>.
    /// </summary>
    [ForeignKey(nameof(ClientId))]
    public Client Client { get; set; } = null!;

    /// <summary>
    /// Collection of service requests raised against this contract.
    /// Initialised to an empty list to avoid null-reference issues.
    /// </summary>
    public ICollection<ServiceRequest> ServiceRequests { get; set; } = new List<ServiceRequest>();
}
